/** Words that describe who, not what: split off so 「小孩發燒」 searches 小孩 + 發燒. */
const WHO = ['小朋友', '小孩', '寶寶', '嬰兒', '老人', '長輩', '阿公', '阿嬤', '孕婦'];

const KEYS = Object.keys(LAY_TERMS).sort((a, b) => b.length - a.length);

/** Split a query word into who + what, e.g. 「老人跌倒」 → ['老人', '跌倒']. */
export const splitWho = (token: string): string[] => {
  for (const w of WHO) {
    if (token !== w && token.startsWith(w)) return [w, ...splitWho(token.slice(w.length))];
    if (token !== w && token.endsWith(w)) return [...splitWho(token.slice(0, -w.length)), w];
  }
  return [token];
};

/** The typed word first, then the terms it stands for. */
export const expandLay = (token: string): string[] => {
  const key = KEYS.find((k) => token.includes(k));
  if (!key) return [token];
  const rest = token.replace(key, '');
  return [token, ...LAY_TERMS[key].map((t) => (rest ? `${t}${rest}` : t)), ...(rest ? LAY_TERMS[key] : [])];
};
