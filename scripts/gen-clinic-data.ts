import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { ALL_DEPARTMENTS, summarizeDepartment } from '../src/data/clinical/full';
import { clinicSearchDocs } from '../src/data/clinical/searchDocs';

/**
 * Snapshots the clinical tree into what the app actually loads (clinic.test.ts fails on drift):
 *  - searchLite.generated.ts — site-search entries, so the search palette stays light;
 *  - catalog.generated.ts    — the light index behind every clinic overview;
 *  - pathways/<dept>.json    — one lazy chunk of full care pathways per department.
 */
const DIR = new URL('../src/data/clinical/', import.meta.url);
const HEADER = '// Generated by scripts/gen-clinic-data.ts — do not edit; run `npm run export:data`.';
const rows = (items: unknown[]) => items.map((x) => `  ${JSON.stringify(x)},`).join('\n');

const docs = clinicSearchDocs();
writeFileSync(
  new URL('searchLite.generated.ts', DIR),
  [HEADER, "import type { SearchDoc } from '../learning/searchIndex';", '', 'export const CLINIC_SEARCH_DOCS: SearchDoc[] = [', rows(docs), '];', ''].join('\n'),
  'utf8'
);

writeFileSync(
  new URL('catalog.generated.ts', DIR),
  [HEADER, "import type { DepartmentSummary } from './types';", '', 'export const DEPARTMENT_INDEX: DepartmentSummary[] = [', rows(ALL_DEPARTMENTS.map(summarizeDepartment)), '];', ''].join('\n'),
  'utf8'
);

const PATHWAYS = new URL('pathways/', DIR);
mkdirSync(PATHWAYS, { recursive: true });
const keep = new Set(ALL_DEPARTMENTS.map((d) => `${d.id}.json`));
for (const f of readdirSync(PATHWAYS)) if (!keep.has(f)) rmSync(new URL(f, PATHWAYS));
for (const d of ALL_DEPARTMENTS) writeFileSync(new URL(`${d.id}.json`, PATHWAYS), `${JSON.stringify(d, null, 2)}\n`, 'utf8');

console.log(`clinic data: ${docs.length} search entries, ${ALL_DEPARTMENTS.length} departments in the index and as pathway chunks`);
